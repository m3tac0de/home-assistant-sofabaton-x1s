// Generates remote-card/src/entity-icons/x2-icons.ts from
// the drawings in scripts/x2-icons/icons.mjs: one minified 24x24 path per X2
// icon id, plus the X1 and X1S icons drawn on their own, keyed by that
// line's icon id. The output is
// committed; rerun after editing an icon (tests/frontend/x2-icons.test.ts
// fails while the two disagree).

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as B from "./x2-icons/geometry.mjs";
import { ICONS, X1_ICONS, X1S_ICONS } from "./x2-icons/icons.mjs";

// fileURLToPath, not URL.pathname: the pathname is percent-encoded, which
// breaks checkouts whose path holds a space or non-ASCII characters.
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "remote-card/src/entity-icons/x2-icons.ts");

const entries = (set) => Object.entries(set).map(([id, [name, draw]]) => `  // ${name}\n  ${id}: "${B.build(draw(B))}",`);
const x2 = entries(ICONS), x1 = entries(X1_ICONS), x1s = entries(X1S_ICONS);
const names = (set) => Object.entries(set).map(([id, [name]]) => `  ${id}: ${JSON.stringify(name)},`);

const source = `// GENERATED by scripts/build-x2-icons.mjs from scripts/x2-icons/icons.mjs. Do not edit by hand.
//
// The X2 activity/device icon set, keyed by the icon id an X2 entity record
// stores (1-${x2.length}). Each value is one path on a 24x24 viewBox with
// nonzero fill, the same contract as @mdi/js, so it renders through
// ha-svg-icon's \`path\` or a plain <svg viewBox="0 0 24 24"><path d="...">.
// The wordmarks (13-16, 35-45) belong to the services they name.

export const X2_ICON_PATHS: Readonly<Record<number, string>> = {
${x2.join("\n")}
};

/** English names of the X2 icons, for labels and tooltips. */
export const X2_ICON_NAMES: Readonly<Record<number, string>> = {
${names(ICONS).join("\n")}
};

// The X1 icons drawn on their own, keyed by the X1 icon id (the X1 numbers
// its own 25 icons): objects the X2 set has none of, or redrew. Same path
// contract; the logos and wordmarks (13, 14, 16, 25) belong to the services
// they name. entity-icons.ts resolves an icon id for any hub line.

export const X1_ICON_PATHS: Readonly<Record<number, string>> = {
${x1.join("\n")}
};

// The X1S icons drawn on their own, keyed by the X1S icon id (the X1S
// shares ids 1-16 with the X2): objects neither the X2 drawing at the same
// id nor any X1 drawing shows. Same path contract; 15 belongs to the
// service it names.

export const X1S_ICON_PATHS: Readonly<Record<number, string>> = {
${x1s.join("\n")}
};
`;

writeFileSync(OUT, source);
const bytes = (set) => Object.values(set).reduce((n, [, draw]) => n + B.build(draw(B)).length, 0);
console.log(`wrote ${OUT} (${x2.length} X2 + ${x1.length} X1 + ${x1s.length} X1S icons, ${bytes(ICONS)} + ${bytes(X1_ICONS)} + ${bytes(X1S_ICONS)} bytes of path data)`);
