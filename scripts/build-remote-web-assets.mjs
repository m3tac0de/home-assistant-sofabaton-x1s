const toExport = (name) => "mdi" + name.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");

const wanted = new Map();
const missing = [];
for (const name of [...cardIcons, ...CURATED]) {
  const key = toExport(name);
  if (typeof mdi[key] === "string") wanted.set(name, key);
  else if (cardIcons.has(name)) missing.push(name);
}
if (missing.length) {
  throw new Error(`card icons missing from @mdi/js: ${missing.join(", ")}`);
}
const sorted = [...wanted.entries()].sort(([a], [b]) => a.localeCompare(b));

