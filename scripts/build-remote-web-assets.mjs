function resolve(map, name, seen = new Set()) {
  const raw = map[name];
  if (raw == null) return null;
  if (seen.has(name)) return null;
  seen.add(name);
  // Replace every var(--x[, fallback]) with its resolved value.
  return String(raw).replace(/var\(--([a-z0-9-]+)(?:,\s*([^)]+))?\)/g, (_m, inner, fallback) => {
    const value = resolve(map, inner, new Set(seen));
    return value ?? (fallback ?? "").trim();
  });
}

/** The palette as data: `--name` to value, for one mode. */
function paletteEntries(mode) {
  const map = mode === "dark" ? { ...base.light, ...base.dark } : base.light;
  const out = {};
  for (const name of CARD_VARS) {
    const value = resolve(map, name);
    if (value == null || value === "") continue;
    out[`--${name}`] = value;
  }
  return out;
}

function palette(mode) {
  return Object.entries(paletteEntries(mode))
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
}

