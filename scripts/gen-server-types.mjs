// Generate sofabaton-x-server/openapi.d.ts from openapi.json (CR-X3-5).
//
// The server panel and the web remote alias these types instead of keeping
// hand-written copies of the wire contract. The file is committed and never
// edited by hand (L-A21); it records the hash of the document it came from,
// so tests/frontend/server-contract.test.ts notices a stale copy without
// running the generator.
//
//   npm run gen:server-types
//
// Fields with a server default are optional (`--default-non-nullable false`):
// request bodies may leave them out, and a panel must cope with a server
// that predates a field anyway.

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATOR = "openapi-typescript@7.13.0";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = join(root, "sofabaton-x-server", "openapi.json");
const output = join(root, "sofabaton-x-server", "openapi.d.ts");

/** The hash the test recomputes: line endings normalised, so a CRLF checkout agrees with CI. */
export function openapiDigest(text) {
  return createHash("sha256").update(text.replace(/\r\n/g, "\n")).digest("hex");
}

function main() {
  const work = mkdtempSync(join(tmpdir(), "server-types-"));
  const generated = join(work, "openapi.d.ts");
  try {
    const run = spawnSync(
      "npx",
      ["--prefer-offline", "-y", GENERATOR, input, "--default-non-nullable", "false", "-o", generated],
      { cwd: root, stdio: "inherit", shell: process.platform === "win32" },
    );
    if (run.status !== 0) {
      console.error(`${GENERATOR} failed (${run.status})`);
      process.exit(run.status ?? 1);
    }
    const header = [
      "// Generated by scripts/gen-server-types.mjs from sofabaton-x-server/openapi.json",
      "// (npm run gen:server-types). Never edit by hand.",
      `// openapi.json sha256: ${openapiDigest(readFileSync(input, "utf8"))}`,
      "",
    ].join("\n");
    const body = readFileSync(generated, "utf8").replace(/\r\n/g, "\n");
    writeFileSync(output, header + body);
    console.log(`wrote ${output}`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
